"""Write docs/tdm-progress.md: which Tarkir: Dragonstorm cards the engine plays, which are next, and which
need a new engine mechanic. Order: commons and uncommons by how often real drafters picked them, then rares.

    python scripts/tdm_progress.py
"""

import json
import re
import subprocess

import numpy as np

from bolt.data import ASSETS, DATA, ROOT

MECHANICS = {
    "behold": r"\bbehold\b", "flurry": r"\bflurry\b", "renew": r"\brenew\b", "mobilize": r"\bmobilize\b",
    "endure": r"\bendures?\b", "harmonize": r"\bharmonize\b", "costs less": r"costs? \{\d\} less|affinity",
    "during your turn": r"during your turn", "once-per-turn mana": r"activate only once each turn",
}  # fmt: skip


def main():
    cards = json.loads((ASSETS / "TDM_oracle.json").read_text())
    picks = np.bincount(np.load(DATA / "TDM_picks.npz")["pick"], minlength=len(cards))
    out = subprocess.run(
        ["cargo", "run", "-q", "--release", "-j", "2", "-p", "bolt-cards", "--example", "set_support", "--", "TDM"],
        cwd=ROOT / "engine",
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    done = {line.split("\t")[1] for line in out.splitlines() if line.startswith("yes")}
    rows = []
    for i, c in enumerate(cards):
        text = re.sub(r"\([^)]*\)", "", c.get("oracle_text") or "")
        needs = [m for m, pat in MECHANICS.items() if re.search(pat, text, re.I)]
        needs += ["omen (two-part card)"] if c["layout"] == "adventure" else []
        needs += ["saga"] if c["layout"] == "saga" else []
        needs += ["{2/C} hybrid cost"] if "{2/" in (c.get("mana_cost") or "") else []
        rank = 0 if c["rarity"] in ("common", "uncommon") else 1
        rows.append((c["name"] in done, rank, -int(picks[i]), c["name"], c["rarity"], needs))
    n_done = sum(r[0] for r in rows)
    lines = [
        "# Tarkir: Dragonstorm in the engine",
        "",
        f"**{n_done} of {len(rows)} cards playable.** Generated by `scripts/tdm_progress.py`; each scripted card has a "
        "test in `engine/bolt-cards/tests/tdm.rs`. Order: commons and uncommons by how often 17lands drafters "
        "picked them, then rares; a set keyword is built once, then every card that uses it.",
        "",
        "## Remaining",
        "",
        "| # | Card | Rarity | Picks | Needs a new mechanic |",
        "|---|---|---|---|---|",
    ]
    for k, r in enumerate(sorted(x for x in rows if not x[0]), 1):
        lines.append(f"| {k} | {r[3]} | {r[4]} | {-r[2]:,} | {', '.join(r[5]) or ''} |")
    lines += ["", "## Done", ""]
    lines += [f"- {r[3]} ({r[4]})" for r in sorted(x for x in rows if x[0])]
    (ROOT / "docs" / "tdm-progress.md").write_text("\n".join(lines) + "\n")
    print(f"{n_done} of {len(rows)} playable")


if __name__ == "__main__":
    main()
