"""Sort every Foundations card by how hard its rules are to implement, and measure how many real
decks each tier of engine support would cover.

    python scripts/card_audit.py

Tiers are assigned from the card's rules text by pattern, so this is a planning estimate, not a
rules ruling. Writes docs/engine/CARD_AUDIT.md and results/card_audit.json.
"""

import json
import re

import numpy as np

from bolt.data import ASSETS, ROOT, load_games

EVERGREEN = {
    "flying", "reach", "vigilance", "trample", "deathtouch", "lifelink", "first strike", "double strike",
    "haste", "menace", "defender", "flash", "hexproof", "indestructible",
}  # fmt: skip
ONE_SHOT = [
    r"deals? \d+ damage", r"destroy target", r"exile target", r"draw (a|two|three) cards?", r"gain \d+ life",
    r"gets? [+-]\d+/[+-]\d+ until end of turn", r"counter target", r"return target .* to (its|their) owner'?s? hand",
    r"create .* token", r"scry \d", r"surveil \d", r"put .* \+1/\+1 counters?", r"target player mills?",
    r"tap target", r"fights? ", r"search your library", r"discard", r"loses? \d+ life",
]  # fmt: skip
COMPLEX = [
    r"\binstead\b", r"\bwould\b", r"\bcopy\b", r"gain control", r"extra turn", r"\bloyalty\b",
    r"you may cast .* from", r"for each", r"\bx\b", r"can't be blocked except", r"phase",
]  # fmt: skip
TIERS = {
    0: "Basic lands",
    1: "Vanilla and keyword-only",
    2: "One-shot effects: spells, enters/dies triggers, simple lands",
    3: "Ongoing rules: other triggers, activated abilities, auras, equipment, anthems, modal",
    4: "Complex: replacement effects, copies, X costs, control change, planeswalkers",
}


def strip_reminders(text: str) -> str:
    return re.sub(r"\([^)]*\)", "", text or "").lower()


def tier_of(card: dict) -> int:
    type_line = card["type_line"] or ""
    if "Basic Land" in type_line:
        return 0
    text = strip_reminders(card["oracle_text"])
    if "kicker" in text:  # "if this spell was kicked ... instead" is ordinary, not a replacement effect
        text = re.sub(r"[^\n.]*kicked[^\n.]*instead[^\n.]*", " kicked ", text)
    if "Planeswalker" in type_line or any(re.search(p, text) for p in COMPLEX) or "X" in (card["mana_cost"] or ""):
        return 4
    lines = [ln.strip(" .") for ln in text.split("\n") if ln.strip()]
    keyword_only = all(all(k.strip() in EVERGREEN for k in ln.split(",")) for ln in lines)
    if "Creature" in type_line and keyword_only:
        return 1
    triggers_ongoing = re.search(r"\bwhenever\b|at the beginning of|\{t\}:|^\{[^}]+\}.*:|equip|enchant |"
                                 r"creatures you control get|choose one|\bas long as\b", text, re.M)  # fmt: skip
    if triggers_ongoing:
        return 3
    simple_land = "Land" in type_line and re.fullmatch(r"[^\n]*enters tapped[\s\S]*", text or "")
    if simple_land or any(re.search(p, text) for p in ONE_SHOT) or keyword_only:
        return 2
    return 3


def main():
    oracle = json.loads((ASSETS / "FDN_oracle.json").read_text())
    tiers = np.array([tier_of(c) for c in oracle])
    g = load_games()
    decks = g["deck"][:, : len(oracle)] > 0
    max_tier = np.where(decks, tiers[None, :], -1).max(1)
    out = {"tiers": {}, "deck_coverage": {}}
    md = [
        "# Card audit: Foundations",
        "",
        "Generated by `scripts/card_audit.py` from Scryfall rules text. Tiers come from pattern-matching",
        "the rules text, so they're a planning estimate. A card can move once someone implements it.",
        "",
        "| Tier | What | Cards | Real decks fully playable with tiers ≤ this |",
        "|---|---|---|---|",
    ]
    for t, desc in TIERS.items():
        n_cards = int((tiers == t).sum())
        cover = float((max_tier <= t).mean())
        out["tiers"][t] = {
            "description": desc,
            "cards": [c["name"] for c, ti in zip(oracle, tiers, strict=True) if ti == t],
        }
        out["deck_coverage"][t] = cover
        md.append(f"| {t} | {desc} | {n_cards} | {cover:.1%} |")
    md += ["", f"Coverage is measured on {len(decks):,} real 17lands decks.", ""]

    # Build order: implement the most-played cards first. How many cards until N% of decks are playable?
    nonbasic = tiers > 0
    order = np.argsort(-(decks[:, nonbasic]).sum(0))
    ids = np.flatnonzero(nonbasic)[order]
    needed = decks[:, nonbasic].sum(1)
    done = np.zeros(len(decks), np.int64)
    curve = []
    for i in ids:
        done += decks[:, i]
        curve.append(float((done == needed).mean()))
    targets = {}
    for goal in (0.25, 0.5, 0.8, 0.95, 1.0):
        targets[goal] = int(np.argmax(np.array(curve) >= goal - 1e-9)) + 1
    out["build_order"] = [oracle[i]["name"] for i in ids]
    out["cards_needed_for_coverage"] = targets
    md += [
        "## Build order",
        "",
        "Implement cards from most-played down. Cards needed for a share of real decks to be fully playable:",
        "",
        "| Decks playable | Cards implemented |",
        "|---|---|",
    ]
    md += [f"| {g:.0%} | {n} of {len(ids)} |" for g, n in targets.items()]
    md += ["", "The 40 most-played cards, in order: " + ", ".join(out["build_order"][:40]) + ".", ""]
    for t, desc in TIERS.items():
        md += [f"## Tier {t}: {desc}", "", ", ".join(sorted(out["tiers"][t]["cards"])), ""]
    (ROOT / "docs" / "engine").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "engine" / "CARD_AUDIT.md").write_text("\n".join(md))
    (ROOT / "results" / "card_audit.json").write_text(json.dumps(out, indent=1))
    print("\n".join(md[5:12]))
    print(out["cards_needed_for_coverage"])


if __name__ == "__main__":
    main()
